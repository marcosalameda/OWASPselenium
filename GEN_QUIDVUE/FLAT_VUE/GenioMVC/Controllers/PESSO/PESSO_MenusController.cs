		// GET: /Pesso/GQT_MenuMC_271
		public ActionResult GQT_MenuMC_271([FromBody]RequestOpenModel requestModel)
		{
			string id = requestModel.Id;
			string formMode = requestModel.FormMode;

			if (Navigation.CurrentLevel != null)
				CSGenio.framework.Audit.registAction(UserContext.Current.User, Resources.Resources.MENU01948 + " " + Navigation.CurrentLevel.Location.ShortDescription());

			Models.Pesso pesso = Models.Pesso.Find(id, UserContext.Current, "ML271");
			Navigation.SetValue("pesso", id);
			if (pesso != null && (((Logical)pesso.ValInterna)==1))
			{
				if (string.IsNullOrEmpty(formMode))
					formMode = "Edit";
				return JsonOK(new { actionName = "MC_2711", id = id });
			}
			if (pesso != null && (((Logical)pesso.ValExterna)==1))
			{
				if (string.IsNullOrEmpty(formMode))
					formMode = "Edit";
				return JsonOK(new { actionName = "MC_2712", id = id });
			}
			else
			{
				if (string.IsNullOrEmpty(formMode))
					formMode = "Show";
				return RedirectToFormAction("PESSO", formMode.ToUpper(), new { id });
			}
		}

