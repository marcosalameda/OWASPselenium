		/// Maps a single CSGenioAwareh row
		/// to a Artiginv_WarehValWarehdes_RowViewModel object.
		/// </summary>
		/// <param name="row">The row.</param>
		private Artiginv_WarehValWarehdes_RowViewModel MapArtiginv_WarehValWarehdes(CSGenioAwareh row)
		{
			var model = new Artiginv_WarehValWarehdes_RowViewModel(m_userContext, true, _fieldsToSerialize);
			if (row == null)
				return model;

			foreach (RequestedField Qfield in row.Fields.Values)
			{
				switch (Qfield.Area)
				{
					case "wareh":
						model.klass.insertNameValueField(Qfield.FullName, Qfield.Value); break;
					default:
						break;
				}
			}

			model.InitRowData();

			return model;
		}

