		}

		/// <inheritdoc />
		public override void MapToModel(Models.Item m)
		{
			if (m == null)
			{
				CSGenio.framework.Log.Error("Map ViewModel (Plist) to Model (Item) - Model is a null reference");
				throw new ModelNotFoundException("Model not found");
			}

			try
			{
				m.ValCodwareh = ViewModelConversion.ToString(ValCodwareh);
				m.ValItemdes = ViewModelConversion.ToString(ValItemdes);
				m.ValCoditem = ViewModelConversion.ToString(ValCoditem);

				/*
					At this moment, in the case of runtime calculation of server-side formulas, to improve performance and reduce database load,
						the values coming from the client-side will be accepted as valid, since they will not be saved and are only being used for calculation.
				*/
				if (!HasDisabledUserValuesSecurity)
					return;

				m.ValCodgitem = ViewModelConversion.ToString(ValCodgitem);
			}
			catch (Exception)
			{
				CSGenio.framework.Log.Error($"Map ViewModel (Plist) to Model (Item) - Error during mapping. All user values: {HasDisabledUserValuesSecurity}");
				throw;
			}
		}

