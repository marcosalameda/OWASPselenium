		/// <inheritdoc />
		public override void MapFromModel(Models.Item m)
		{
			if (m == null)
			{
				CSGenio.framework.Log.Error("Map Model (Item) to ViewModel (Plist) - Model is a null reference");
				throw new ModelNotFoundException("Model not found");
			}

			try
			{
				ValCodgitem = ViewModelConversion.ToString(m.ValCodgitem);
				ValCodwareh = ViewModelConversion.ToString(m.ValCodwareh);
				ValItemdes = ViewModelConversion.ToString(m.ValItemdes);
				funcGitemValItemdes = () => ViewModelConversion.ToString(m.Gitem.ValItemdes);
				ValCoditem = ViewModelConversion.ToString(m.ValCoditem);
			}
			catch (Exception)
			{
				CSGenio.framework.Log.Error("Map Model (Item) to ViewModel (Plist) - Error during mapping");
				throw;
			}
		}

		/// <inheritdoc />
		public override void MapToModel()
