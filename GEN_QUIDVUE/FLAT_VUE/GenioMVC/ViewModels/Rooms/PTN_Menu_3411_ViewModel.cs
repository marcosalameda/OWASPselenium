		private List<PTN_Menu_3411_RowViewModel> MapPTN_Menu_3411(ListingMVC<CSGenioArooms> Qlisting)
		{
			var Elements = new List<PTN_Menu_3411_RowViewModel>();
			int i = 0;

			if (Qlisting.Rows != null)
			{
				foreach (var row in Qlisting.Rows)
				{
					if (Qlisting.NumRegs > 0 && i >= Qlisting.NumRegs) // Copiado da versão antiga do RowsToViewModels
						break;
					Elements.Add(MapPTN_Menu_3411(row));
					i++;
				}
			}

			return Elements;
		}


