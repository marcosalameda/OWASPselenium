// USE /[MANUAL PTN OVERRQLIST 3411]/

					string QMVC_POS_RECORD = Navigation.GetStrValue("QMVC_POS_RECORD_rooms");
					Navigation.DestroyEntry("QMVC_POS_RECORD_rooms");
